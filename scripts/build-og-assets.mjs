/**
 * Generates the committed assets the dynamic OG route needs at runtime, so the
 * Worker carries no build-time font tooling (spec §33.A):
 *
 *   src/lib/og-fonts.ts     — Departure Mono decompressed woff2 → OTF, base64.
 *   src/lib/og-fallback.ts  — a baked BEAT card PNG, base64 (served if the live
 *                             render ever throws, so /og/beat.png never 500s).
 *
 * satori needs sfnt (ttf/otf) and the repo ships only woff2, so we decompress
 * with the MIT `wawoff2` decoder (a devDependency — never shipped to the edge).
 * Zero paid deps, no new font binaries fetched. Re-run after a font change:
 *   node scripts/build-og-assets.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import * as wawoff from 'wawoff2';
import { renderBeatPng, initEngines } from '../src/lib/og-card.mjs';

const require = createRequire(import.meta.url);

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const p = (rel) => new URL(rel, `file://${ROOT}`).pathname;

const GENERATED = '// GENERATED by scripts/build-og-assets.mjs — do not edit by hand.\n';
const DECODE = `function b64(s: string): Uint8Array {
  const bin = atob(s);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}\n`;

// ── 1. Departure Mono woff2 → OTF → base64 module ──────────────────────────
const woff2 = await readFile(p('public/fonts/departure-mono.woff2'));
const otf = Buffer.from(await wawoff.decompress(woff2));
const tag = otf.subarray(0, 4).toString('hex');
if (tag !== '4f54544f' && tag !== '00010000') throw new Error(`unexpected sfnt tag ${tag}`);
console.log(`departure-mono: woff2 ${woff2.length}B → otf ${otf.length}B (sfnt ${tag})`);

await writeFile(
  p('src/lib/og-fonts.ts'),
  GENERATED +
    '// Departure Mono (OFL) as OTF base64, decoded at module load for satori.\n' +
    DECODE +
    `export const DEPARTURE_MONO_OTF_B64 =\n  '${otf.toString('base64')}';\n` +
    'export const DEPARTURE_MONO_OTF = b64(DEPARTURE_MONO_OTF_B64);\n' +
    "export const OG_FONTS = [\n" +
    "  { name: 'Departure Mono', data: DEPARTURE_MONO_OTF, weight: 400 as const, style: 'normal' as const },\n" +
    '];\n',
);
console.log('wrote src/lib/og-fonts.ts');

// ── 2. baked fallback PNG (rendered here with the same pipeline) ────────────
// init both engines from the on-disk wasm; in Node async instantiate is fine.
const yogaWasm = await readFile(require.resolve('satori/yoga.wasm'));
const resvgWasm = await readFile(p('node_modules/@resvg/resvg-wasm/index_bg.wasm'));
await initEngines(yogaWasm, resvgWasm);
const fonts = [{ name: 'Departure Mono', data: otf, weight: 400, style: 'normal' }];
const baseState = {
  value: 'BEAT',
  suffix: '',
  label: 'the pulse of Ethereum',
  slot: NaN,
  asOf: null,
};
// one baked card per theme, so the never-500 fallback matches ?theme= (spec §33.A).
const light = await renderBeatPng({ ...baseState, theme: 'light' }, fonts);
const dark = await renderBeatPng({ ...baseState, theme: 'dark' }, fonts);
for (const [name, png] of [['light', light], ['dark', dark]]) {
  if (png[0] !== 0x89 || png[1] !== 0x50) throw new Error(`${name} fallback render did not produce a PNG`);
  console.log(`fallback card (${name}): ${png.length}B PNG`);
}

await writeFile(
  p('src/lib/og-fallback.ts'),
  GENERATED +
    '// Baked BEAT cards (one per theme), served by /og/beat.png if the live render throws.\n' +
    DECODE +
    `export const OG_FALLBACK_PNG_B64 =\n  '${Buffer.from(light).toString('base64')}';\n` +
    'export const OG_FALLBACK_PNG = b64(OG_FALLBACK_PNG_B64);\n' +
    `export const OG_FALLBACK_PNG_DARK_B64 =\n  '${Buffer.from(dark).toString('base64')}';\n` +
    'export const OG_FALLBACK_PNG_DARK = b64(OG_FALLBACK_PNG_DARK_B64);\n',
);
console.log('wrote src/lib/og-fallback.ts');
